// `next build` with output: "standalone" does not copy public/ or .next/static,
// and its generated .next/standalone/server.js does `process.chdir(__dirname)`
// before doing anything else — so DATA_DIR/DEM_DATA_DIR's defaults
// (process.cwd()/data/...) would resolve inside .next/standalone, which we
// wipe below on every build. This script makes .next/standalone fully
// self-contained AND makes its server.js safe to use as a Plesk startup file
// directly, by wrapping the Next-generated entry point with env vars anchored
// to the project root.
import { cpSync, existsSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = process.cwd();
const standalone = path.join(root, ".next", "standalone");

if (!existsSync(standalone)) {
  console.error("[postbuild] .next/standalone not found — is output: 'standalone' set?");
  process.exit(1);
}

// Runtime snapshots must never ship inside the build.
rmSync(path.join(standalone, "data"), { recursive: true, force: true });

cpSync(path.join(root, "public"), path.join(standalone, "public"), { recursive: true });
cpSync(path.join(root, ".next", "static"), path.join(standalone, ".next", "static"), {
  recursive: true,
});

// Wrap Next's generated server.js so DATA_DIR/HOSTNAME are correct no matter
// which entry point a host is pointed at: the project-root server.js (which
// just requires this file) or .next/standalone/server.js directly.
const generatedServer = path.join(standalone, "server.js");
const originalServer = path.join(standalone, "server.original.js");
writeFileSync(originalServer, readFileSync(generatedServer, "utf8"));
writeFileSync(
  generatedServer,
  `// Auto-generated by scripts/postbuild-standalone.mjs on every build — do not edit by hand.
// Safe to point a host's startup file at THIS file directly (no separate
// project-root server.js required), because the anchoring below happens
// before Next's original generated server (now server.original.js) runs.

// The standalone server binds to $HOSTNAME, which is the machine name on many
// hosts and then refuses localhost/proxy traffic — bind to all interfaces
// unless told otherwise.
process.env.HOSTNAME = process.env.BIND_HOST || "0.0.0.0";

// Next's generated server does process.chdir(__dirname) into .next/standalone,
// and this build script wipes .next/standalone/data on every build. Anchor
// DATA_DIR and DEM_DATA_DIR two levels up (the project root) so snapshots/
// history and downloaded DEM tiles survive rebuilds instead of silently
// resetting. Only wrong if this .next/standalone folder was copied out from
// under its project root — set these env vars yourself in that deployment
// instead.
const path = require("node:path");
process.env.DATA_DIR ||= path.join(__dirname, "..", "..", "data", "snapshots");
process.env.DEM_DATA_DIR ||= path.join(__dirname, "..", "..", "data", "dem-src");

require("./server.original.js");
`,
);

console.log(
  "[postbuild] copied public/ and .next/static into .next/standalone, wrapped server.js",
);
